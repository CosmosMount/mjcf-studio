  worldAxis?: V3;
  geometry?: MeshData;
  rgba?: number[];
  size?: number[];
  texture?: string;
  appearance?: Record<string, any>;
  mesh?: string;
  com?: V3;
  inertia?: number[];
  inertialQuat?: number[];
